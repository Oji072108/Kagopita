window.KagopitaI18n = (() => {
  const textState = new WeakMap();
  const attrState = new WeakMap();
  let activeLanguage = 'ja', activeDictionary = {};
  const terms = {
    ja: ['件中', '件を表示', '担当', '追加', '使用中', '設定中', 'を編集', 'を削除'],
    en: ['of', 'items shown', 'Assigned', 'Added by', 'Current', 'Active', 'Edit', 'Delete'],
    ko: ['개 중', '개 표시', '담당', '추가', '사용 중', '설정 중', '편집', '삭제'],
    zh: ['件中', '件显示', '负责人', '添加者', '当前使用', '已设置', '编辑', '删除'],
    es: ['de', 'artículos visibles', 'Responsable', 'Añadido por', 'Actual', 'Activo', 'Editar', 'Eliminar']
  };
  function translateString(source, language, dictionary) {
    if (language === 'ja') return source;
    if (dictionary[source]) return dictionary[source];
    const t = terms[language] || terms.en;
    let m;
    if ((m = source.match(/^(\d+)件中 (\d+)件を表示$/))) return ({en: `${m[2]} of ${m[1]} items shown`, ko: `${m[1]}개 중 ${m[2]}개 표시`, zh: `显示 ${m[2]} / ${m[1]} 件`, es: `${m[2]} de ${m[1]} artículos visibles`})[language];
    if ((m = source.match(/^(担当|追加): (.*)$/))) return `${t[m[1] === '担当' ? 2 : 3]}: ${dictionary[m[2]] || m[2]}`;
    if ((m = source.match(/^使用中: (.*)$/))) return `${t[4]}: ${m[1]}`;
    if (source === '✓ 使用中') return `✓ ${t[4]}`;
    if ((m = source.match(/^(.*)を(編集|削除)$/))) return `${t[m[2] === '編集' ? 6 : 7]}: ${m[1]}`;
    if ((m = source.match(/^(.*)の完了状態を切り替え$/))) return `${({en:'Mark purchased',ko:'구매 상태 변경',zh:'切换购买状态',es:'Marcar comprado'})[language]}: ${m[1]}`;
    if ((m = source.match(/^(.*)をお気に入りに追加$/))) return `${dictionary['お気に入り'] || 'Favorites'} + ${m[1]}`;
    if ((m = source.match(/^(.*)をお気に入りから削除$/))) return `${dictionary['お気に入り'] || 'Favorites'} − ${m[1]}`;
    return source;
  }
  function translate(root, language, dictionary) {
    activeLanguage = language; activeDictionary = dictionary;
    root.querySelectorAll('[data-shopping-name],[data-shopping-quantity],[data-shopping-category]').forEach(element => {
      const data = element.dataset;
      let translated;
      if (data.shoppingName !== undefined) {
        translated = window.KagopitaShoppingLanguage.translate(data.shoppingName, language);
        element.title = translated !== data.shoppingName ? data.shoppingName : '';
      } else if (data.shoppingCategory !== undefined) {
        translated = dictionary[data.shoppingCategory] || window.KagopitaShoppingLanguage.translate(data.shoppingCategory, language);
      } else {
        translated = (data.shoppingPrefix || '') + window.KagopitaQuantity.display(data.shoppingItem, data.shoppingQuantity, language) + (data.shoppingSuffix || '');
      }
      if (element.textContent !== translated) element.textContent = translated;
    });
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script,style,textarea,.item-name,.joined-channel-name,.member-name,.feed-avatar,#activeListLabel,[data-language],[data-i18n-ignore="true"]')) continue;
      const current = node.nodeValue.trim();
      if (!current) continue;
      const saved = textState.get(node);
      const source = parent.dataset.i18nSource || (saved?.last === current ? saved.source : current);
      if (parent.tagName === 'OPTION' && !parent.dataset.i18nSource) parent.dataset.i18nSource = source;
      const translated = translateString(source, language, dictionary);
      textState.set(node, {source, last: translated});
      if (current !== translated) node.nodeValue = node.nodeValue.replace(current, translated);
    }
    root.querySelectorAll('[placeholder],[aria-label],[title]').forEach(element => {
      const state = attrState.get(element) || {};
      for (const attribute of ['placeholder','aria-label','title']) {
        const current = element.getAttribute(attribute); if (!current) continue;
        const saved = state[attribute];
        const source = saved?.last === current ? saved.source : current;
        const translated = translateString(source, language, dictionary);
        state[attribute] = {source, last: translated};
        if (current !== translated) element.setAttribute(attribute, translated);
      }
      attrState.set(element, state);
    });
    document.documentElement.lang = language;
    const suffix = ({ja:'（設定中）',en:' (active)',ko:' (설정 중)',zh:'（已设置）',es:' (activo)'})[language];
    document.documentElement.style.setProperty('--filter-active-label', JSON.stringify(suffix));
  }
  let queued = false;
  new MutationObserver(() => {
    if (queued) return;
    queued = true;
    queueMicrotask(() => { queued = false; translate(document.body, activeLanguage, activeDictionary); });
  }).observe(document.body, {subtree: true, childList: true, characterData: true});
  return {translate};
})();
